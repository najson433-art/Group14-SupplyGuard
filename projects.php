
<?php
require_once __DIR__ . '/../includes/bootstrap.php';
require_once __DIR__ . '/../includes/scan_service.php';
require_once __DIR__ . '/../includes/view_helpers.php';

require_developer();

$uid = (int) current_user()['user_id'];

// Handle project actions.
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    verify_csrf();

    $action = (string) ($_POST['action'] ?? 'create');
    $id = (int) ($_POST['project_id'] ?? 0);

    // Delete a project and its uploaded manifest files.
    if ($action === 'delete') {
        $project = project_owned($pdo, $id);

        if (!$project) {
            http_response_code(404);
            exit('Project not found.');
        }

        $q = $pdo->prepare(
            'SELECT file_path
             FROM dependency_files
             WHERE project_id = ?'
        );

        $q->execute([$id]);
        $paths = $q->fetchAll(PDO::FETCH_COLUMN);

        $delete = $pdo->prepare(
            'DELETE FROM projects
             WHERE project_id = ? AND user_id = ?'
        );

        $delete->execute([$id, $uid]);

        if ($delete->rowCount() > 0) {
            foreach ($paths as $path) {
                // Stored manifest names are generated by the application.
                // Restrict deletion to files directly inside UPLOAD_DIR.
                $filename = basename((string) $path);
                $fullPath = UPLOAD_DIR . DIRECTORY_SEPARATOR . $filename;

                if (
                    $filename !== '' &&
                    $filename === (string) $path &&
                    is_file($fullPath)
                ) {
                    @unlink($fullPath);
                }
            }

            flash(
                'success',
                'Project and its stored manifest files were deleted.'
            );
        } else {
            flash('danger', 'The project could not be deleted.');
        }

        go('projects.php');
    }

    // Validate project details for creation or editing.
    if (!in_array($action, ['create', 'edit'], true)) {
        http_response_code(400);
        exit('Invalid project action.');
    }

    $name = trim((string) ($_POST['name'] ?? ''));
    $desc = trim((string) ($_POST['description'] ?? ''));

    if ($name === '' || strlen($name) > 150) {
        flash(
            'danger',
            'Project name must contain 1–150 characters.'
        );

        go('projects.php');
    }

    if ($action === 'edit') {
        $project = project_owned($pdo, $id);

        if (!$project) {
            http_response_code(404);
            exit('Project not found.');
        }
    }

    // Prevent duplicate project names within the same account.
    $duplicateCheck = $pdo->prepare(
        'SELECT project_id
         FROM projects
         WHERE user_id = ?
           AND LOWER(name) = LOWER(?)
           AND project_id <> ?
         LIMIT 1'
    );

    $duplicateCheck->execute([
        $uid,
        $name,
        $action === 'edit' ? $id : 0
    ]);

    if ($duplicateCheck->fetchColumn()) {
        flash(
            'danger',
            'You already have a project with this name. Project names must be unique within your account.'
        );

        go('projects.php');
    }

    // Update an existing project.
    if ($action === 'edit') {
        $update = $pdo->prepare(
            'UPDATE projects
             SET name = ?, description = ?
             WHERE project_id = ? AND user_id = ?'
        );

        $update->execute([
            $name,
            $desc,
            $id,
            $uid
        ]);

        flash('success', 'Project updated.');

        go('project.php?id=' . $id);
    }

    // Create a new project.
    $insert = $pdo->prepare(
        'INSERT INTO projects (user_id, name, description)
         VALUES (?, ?, ?)'
    );

    $insert->execute([
        $uid,
        $name,
        $desc
    ]);

    $newProjectId = (int) $pdo->lastInsertId();

    flash('success', 'Project created.');

    go('project.php?id=' . $newProjectId);
}

// Retrieve projects belonging to the logged-in Developer.
$q = $pdo->prepare(
    'SELECT *
     FROM projects
     WHERE user_id = ?
     ORDER BY created_at DESC'
);

$q->execute([$uid]);
$projects = $q->fetchAll(PDO::FETCH_ASSOC);

page_header('My Projects');
